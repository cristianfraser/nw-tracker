-- Vendor catalog (vendorCatalog.ts): how a name the bank, a receipt or a transfer mail prints is
-- shown on an expense row. match_kind: exact (folded name equals the pattern), prefix (starts
-- with it), branch (the pattern, or the pattern + a space + a branch: «Brand (Branch)»), rut (a
-- transfer counterparty's RUT, digits + verifier). Patterns are folded: upper case, no accents,
-- single spaces. The generic brands below are seed rows. The user's own entries (people, RUTs,
-- places) are personal data, loaded on the live database only (scripts/load-vendor-catalog.ts,
-- source = user), and are matched before seed rows.
CREATE TABLE IF NOT EXISTS vendor_catalog (
  id INTEGER PRIMARY KEY,
  match_kind TEXT NOT NULL CHECK (match_kind IN ('exact', 'prefix', 'branch', 'rut')),
  pattern TEXT NOT NULL CHECK (pattern <> ''),
  display TEXT NOT NULL CHECK (display <> ''),
  source TEXT NOT NULL CHECK (source IN ('seed', 'user')),
  UNIQUE (match_kind, pattern, source)
);

